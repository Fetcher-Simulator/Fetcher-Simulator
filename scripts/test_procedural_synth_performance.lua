local M=dofile('files/server/server-lua-packages/fetcher.procedural-synth/client/performance-notes.lua')
local count=0;local function check(x,why) count=count+1;assert(x,why) end
local function row(note,string,fretAge,stamp,layout,held,direction,transpose,track)
 return {note=note,stringSelect=string or 0,age=fretAge or 0,stamp=stamp or 0,layout=layout or 1,
    held=held~=false,direction=direction or 0,transpose=transpose or 0,track=track or 1}
end
local plan,state=M.strings({row(64,1),row(64,6)},'guitar')
check(plan.strings[1].fret==24 and plan.strings[6].fret==0,'same-pitch string unisons keep two physical fret locations')
check(plan.frets[1] and #plan.frets[1]==1 and plan.frets[1][1]==1,'open strings do not invent a fretting finger')
check(plan.strum and plan.pulse==1,'simultaneous chord attacks produce one strumming gesture')
plan,state=M.strings({row(40,1,0,1,2,true,1,-2)},'guitar',state)
check(plan.strings[1].fret==0 and not next(plan.frets) and plan.direction==1,'drop tuning, transpose, open strings and saved upstroke are honored')
plan=M.strings({row(44,0),row(57,0)},'guitar')
check(plan.strings[1] and plan.strings[4] and not plan.strings[2],'visual Auto finds available playable strings without changing pitch')
plan=M.strings({row(20,1)},'guitar')
check(not next(plan.strings),'impossible explicit fingering is not silently remapped to another string')
plan=M.strings({row(23,1,.8,1,6)},'bass')
check(plan.stringCount==5 and plan.strings[1].fret==0 and plan.pulse==0,'long held five-string bass retains tuning without retriggering a pluck')
plan,state=M.strings({row(38,3,0,5,5)},'bass')
local finger=plan.pickFinger
plan,state=M.strings({row(38,3,.04,5,5)},'bass',state)
check(plan.pickFinger==finger and plan.pulse<1,'polling a held bass note does not alternate fingers again')
plan,state=M.strings({row(38,3,0,6,5)},'bass',state)
check(plan.pickFinger~=finger,'a repeated bass pitch alternates plucking fingers')
plan=M.strings({row(64,6,.5,0,1,false)},'guitar')
check(plan.pulse==0 and not next(plan.strings),'released/stale notes do not reanimate fretting or picking')
local d,s=M.drums({row(36,0,.01,1)},100)
check(d.feet.R>0 and d.feet.L==0 and d.hands.L.pulse==0 and d.hands.R.pulse==0,'kick drives only the right foot')
d,s=M.drums({row(44,0,.01,2)},100.02,s)
check(d.feet.L>.08 and d.hands.L.pulse==0 and d.hands.R.pulse==0,'pedal hi-hat drives the left foot without a stick hit')
d,s=M.drums({row(42,0,.01,3)},100.04,s)
check(d.hands.L.note==42 and d.hands.L.pulse>0 and d.hands.R.pulse==0,'closed hi-hat uses its own stick')
d,s=M.drums({row(46,0,.01,4)},100.06,s)
check(d.feet.L<.01,'open hi-hat releases the pedal')
d,s=M.drums({row(38,0,0,5)},100.07,s)
check(d.hands.R.note==38 and d.hands.R.pulse==1,'snare does not displace the freshly active hat stick')
d,s=M.drums({},101,s)
check(d.hands.R.pulse==0 and d.feet.R==0,'stale hit histories settle naturally')
local stopped={playing=false};d,s=M.drums(stopped,102,s)
check(d.feet.L==0 and d.feet.R==0 and d.hands.L.pulse==0 and d.hands.R.pulse==0,'Stop clears feet and sticks')
d,s=M.drums({row(38,0,0,10),row(49,0,0,10)},103)
check(d.hands.L.note==49 and d.hands.R.note==38 and d.hands.L.pulse==1 and d.hands.R.pulse==1,'left crash and central snare get reachable separate sticks')
d,s=M.drums({row(38,0,0,20)},104)
local first=d.hands.R.pulse==1 and 'R' or 'L'
d,s=M.drums({row(38,0,0,21)},104.2,s)
check(d.hands[first].pulse==0 and d.hands[first=='R' and 'L' or 'R'].pulse==1,'repeated single drums alternate hands')
print('PASS native-note visual interpretation: saved string/fret/stroke, open strings, bass fingers, independent sticks/pedals and cleanup; '..count..' assertions')
