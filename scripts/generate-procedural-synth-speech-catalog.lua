-- Reuse the /s and /speech catalogs as searchable metadata, never audio payloads.
-- Run from the repository root with Lua 5.1 or newer.
local files={'speech_data','starwind_speech_data','custom_speech_data'}
local entries={}
local function walk(value,labels)
    if type(value)~='table' then return end
    if type(value[2])=='string' and value[2]:lower():match('%.mp3$') then
        local path=value[2]:gsub('\\','/'):lower()
        if path:sub(1,6)~='sound/' then path='sound/'..path end
        local text=table.concat(labels,' / ')
        if not entries[path] or text<entries[path] then entries[path]=text end
        return
    end
    for key,child in pairs(value) do
        local nextLabels={};for n,label in ipairs(labels) do nextLabels[n]=label end
        if type(key)=='string' then nextLabels[#nextLabels+1]=key end
        walk(child,nextLabels)
    end
end
for _,name in ipairs(files) do walk(dofile('apps/openmw-server/scripts/'..name..'.lua'),{name:gsub('_data','')}) end
local paths={};for path in pairs(entries) do paths[#paths+1]=path end;table.sort(paths)
local groups={}
for _,path in ipairs(paths) do
    local prefix,name=path:match('^(.-/)([^/]+)$');local key=prefix..'|'..entries[path]
    groups[key]=groups[key] or {prefix=prefix,tags=entries[path],names={}}
    table.insert(groups[key].names,name)
end
local keys={};for key in pairs(groups) do keys[#keys+1]=key end;table.sort(keys)
local out=assert(io.open('files/server/server-lua-packages/fetcher.procedural-synth/client/speech-catalog.lua','wb'))
out:write('-- Generated by scripts/generate-procedural-synth-speech-catalog.lua from the server /s catalogs.\n',
    'local M={}\nlocal function group(prefix,tags,names) for name in names:gmatch("[^\\n]+") do M[prefix..name]=tags end end\n')
for _,key in ipairs(keys) do local g=groups[key];local names=table.concat(g.names,'\n');assert(not names:find(']]',1,true))
    out:write(string.format('group(%q,%q,[[%s]])\n',g.prefix,g.tags,names)) end
out:write('return M\n');out:close();print('Speech metadata: '..#paths..' paths / '..#keys..' compact groups')
